import type { Eight, HistoryEvent, Observation, Transfer } from "@/lib/model";
import { independentObservers } from "@/lib/model";

let seq = 1;
function hid(prefix: string) {
  seq += 1;
  return `${prefix}-${seq}`;
}

function obs(by: string, at: string, text: string): Observation {
  return { id: hid("o"), by, at, text };
}

function stamp(entry: Omit<Eight, "history">): Eight {
  const history: HistoryEvent[] = [
    {
      id: hid("h"),
      at: entry.createdAt,
      kind: "created",
      text: entry.anchor
        ? "Зафіксовано якір протоколу. Без ціни і без права передачі."
        : `Запис створено в місті ${entry.city}.`,
    },
  ];
  if (entry.state === "submitted") {
    history.push({
      id: hid("h"),
      at: entry.createdAt,
      kind: "submitted",
      text: "Опис дії і доказ надіслано. Верифікація ще не є автоматичною.",
    });
  }
  for (const observation of entry.observations) {
    history.push({
      id: hid("h"),
      at: observation.at,
      kind: "observation",
      text: `${observation.by} описав, що бачив. Це не оцінка популярності.`,
    });
  }
  const probe = { ...entry, history: [] } as Eight;
  if (!entry.anchor && independentObservers(probe).length >= 2) {
    const at = entry.observations[entry.observations.length - 1]?.at ?? entry.createdAt;
    history.push({
      id: hid("h"),
      at,
      kind: "verified",
      text: "Два незалежні спостереження. Запис верифіковано і він лишається активним на карті.",
    });
  }
  if (entry.anchor) {
    history.push({
      id: hid("h"),
      at: entry.createdAt,
      kind: "verified",
      text: "Якір видимий завжди. Його не підтверджують лайком і не виставляють на обмін.",
    });
  }
  for (const transfer of entry.transfers) {
    history.push({
      id: hid("h"),
      at: transfer.at,
      kind: "transfer",
      text: `${transfer.from} передав контроль до ${transfer.to}. Історія не стирається.`,
    });
  }
  history.sort((a, b) => a.at.localeCompare(b.at));
  return { ...entry, history };
}

